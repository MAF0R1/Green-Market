# Главная функция
def import_products():
    # Ищем файл
    possible_names = ['products.txt', 'products.csv', 'name, price, category.txt', 'name,price,category.txt']

    csv_file = None
    for name in possible_names:
        if os.path.exists(name):
            csv_file = name
            print(f"📂 Найден файл: {name}")
            break

    if not csv_file:
        print("❌ Файл не найден!")
        print(f"📋 Файлы в папке: {os.listdir('.')}")
        return

    try:
        with open(csv_file, 'r', encoding='utf-8') as f:
            lines = f.readlines()

        print(f"📋 Всего строк в файле: {len(lines)}")

        if len(lines) < 2:
            print("❌ Файл пустой или нет данных!")
            return

        # Пропускаем заголовок
        total = 0
        created_products = 0
        updated_products = 0
        categories_created = 0
        category_stats = {}

        print("🔄 Начинаем импорт...")

        for i, line in enumerate(lines[1:], start=2):
            line = line.strip()
            if not line:
                continue

            # Разбиваем по запятой
            parts = line.split(',')
            if len(parts) < 3:
                print(f"⚠️ Строка {i}: пропущено (мало частей: {len(parts)})")
                continue

            name = parts[0].strip().strip('"')
            if not name:
                continue

            try:
                price = float(parts[1].strip().strip('"'))
            except ValueError:
                print(f"⚠️ Строка {i}: ошибка цены - '{parts[1]}'")
                continue

            # Определяем категорию
            category_name = detect_category(name)

            if category_name not in category_stats:
                category_stats[category_name] = 0
            category_stats[category_name] += 1

            # Получаем или создаем категорию
            category, is_new = Category.objects.get_or_create(name=category_name)
            if is_new:
                categories_created += 1
                print(f"📁 Создана категория: {category_name}")

            # Создаем или обновляем товар
            product, is_created = Product.objects.update_or_create(
                name=name,
                defaults={
                    'price': int(price),
                    'category': category,
                    'hit_score': 0,
                }
            )

            total += 1
            if is_created:
                created_products += 1
            else:
                updated_products += 1

            if total % 50 == 0:
                print(f"⏳ Обработано {total} товаров...")

        print("\n" + "=" * 60)
        print("✅ ГОТОВО!")
        print("=" * 60)
        print(f"📊 Всего товаров: {total}")
        print(f"🆕 Создано новых: {created_products}")
        print(f"🔄 Обновлено: {updated_products}")
        print(f"📁 Создано категорий: {categories_created}")
        print("\n📈 Статистика по категориям:")
        print("-" * 40)
        for cat_name, count in sorted(category_stats.items(), key=lambda x: x[1], reverse=True):
            print(f"  {cat_name}: {count} товаров")
        print("=" * 60)

    except Exception as e:
        print(f"❌ Ошибка: {e}")
        import traceback
        traceback.print_exc()


if __name__ == '__main__':
    import_products()